export default function ExamsTabs() {
  const [active, setActive] = useState(exams[0].id);

  return (
    <div>
      <div className="tab-buttons" role="tablist">
        {exams.map((exam) => (
          <button
            key={exam.id}
            role="tab"
            type="button"
            aria-selected={active === exam.id}
            className={active === exam.id ? "tab-btn active" : "tab-btn"}
            onClick={() => setActive(exam.id)}
          >
            {exam.label}
          </button>
        ))}
      </div>
      {exams.map((exam) => (
        <div
          key={exam.id}
          role="tabpanel"
          className={active === exam.id ? "tab-panel active" : "tab-panel"}
        >
          <h2>{exam.title}</h2>
          {exam.body}
        </div>
      ))}
    </div>
  );
}
